#!/usr/bin/env python3
"""Copies the core's table of known BIOS images (MD5 and description) into src/core/bios_hashes.inc.

The core (third_party/swanstation/src/core/bios.cpp) identifies a BIOS by the MD5 of its contents; the BIOS choices of
Settings show the same description. Run it again when the submodule's table changes.
SPDX-License-Identifier: GPL-3.0-or-later
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "third_party/swanstation/src/core/bios.cpp"
OUT = ROOT / "src/core/bios_hashes.inc"

text = SRC.read_text()
block = text[text.index("s_image_infos"):]
block = block[: block.index("};")]
entries = re.findall(r'\{"([^"]+)",\s*ConsoleRegion::\w+,\s*MakeHashFromString\("([0-9a-f]{32})"\)', block)
if not entries:
    raise SystemExit("no BIOS images found in bios.cpp")
lines = ["/* Generated by tools/gen_bios_hashes.py from the core's bios.cpp - do not edit. MD5, description. */"]
lines += ['    {"%s", "%s"},' % (md5, desc.replace("\\", "\\\\").replace('"', '\\"')) for desc, md5 in entries]
OUT.write_text("\n".join(lines) + "\n")
print(f"{len(entries)} BIOS images -> {OUT.relative_to(ROOT)}")
